import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const app=read('public/app.js');
const shell=read('lib/site-shell.ts');
const page=read('lib/reviews-page.ts');
const client=read('public/reviews.js');
const widget=read('public/review-experience.js');
const style=read('public/review-experience.css');
const reviewStyle=read('public/reviews.css');
const edge=read('supabase/functions/veloryz-reviews-api/index.ts');
const proxy=read('lib/cms-api.mjs');

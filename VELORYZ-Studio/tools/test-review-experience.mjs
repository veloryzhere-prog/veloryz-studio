for(const [name,source] of [['review client',client],['review experience',widget],['homepage app',app]])assert.doesNotThrow(()=>new vm.Script(source,{filename:name}),name+' must parse as JavaScript');
const compiled=ts.transpileModule(page,{fileName:'reviews-page.ts',compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.deepEqual((compiled.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error).map(d=>ts.flattenDiagnosticMessageText(d.messageText,'\n')),[]);
const e={exports:{}};vm.runInNewContext(compiled.outputText,{exports:e.exports,module:e},{timeout:1500});
const html=e.exports.renderReviewsPage(false);
for(const field of ['name="name"','name="rating"','name="headline"','name="service"','name="highlights"','name="improvement"','name="review"'])assert.ok(html.includes(field),field+' is missing from detailed review form.');
assert.match(html,/human-moderated/i,'Disclose human moderation.');
assert.match(html,/review-ai-button/,'AI coach is opt-in');
assert.match(html,/data-review-rating="5"/,'Five-star feedback is filterable');
assert.match(html,/data-review-rating="1"/,'One-star feedback is filterable');
assert.match(html,/id="review-start"/,'Start Rating must be immediately visible');
assert.match(html,/id="share-review"[^>]*hidden/,'Detailed form starts collapsed');
assert.doesNotMatch(html,/THE PEOPLE \/ THE PROJECTS|Your words\.<br>|Our next chapter/,'Remove the oversized marketing hero');
assert.match(html,/review-rating-distribution/,'Real rating breakdown');
assert.match(reviewStyle,/#fa7348|--accent:#fa7348/,'Use official warm orange VELORYZ accent');
assert.match(client,/textContent/,'Review text must remain escaped');
assert.doesNotMatch(client,/innerHTML\s*=/,'Do not insert visitor or model content as HTML');
assert.match(client,/\/api\/reviews\/assist/,'Wording helper calls the authenticated-origin API');
assert.match(edge,/GEMINI_API_KEY/,'Provider credentials stay server-side');
assert.match(edge,/await throttle\(req,'ai-assist',8,3600\)/,'AI requests are bounded per client');
assert.match(edge,/NEVER invent a purchase/,'AI must not fabricate experiences');
assert.match(edge,/humanReviewRequired:true/,'AI suggestions never auto-publish');
assert.match(edge,/status='approved'/,'Only approved testimonials may appear on public pages');
assert.match(edge,/await throttle\(req,'submit',3,86400\)/,'Submissions are rate-limited');
assert.match(proxy,/path==='\/api\/reviews\/assist'/,'AI must go through same-origin proxy');
assert.match(schema,/ADD COLUMN IF NOT EXISTS headline/);
assert.match(schema,/ADD COLUMN IF NOT EXISTS highlights/);
assert.match(schema,/REVOKE ALL ON veloryz_studio\.studio_reviews FROM PUBLIC,anon,authenticated/);
assert.match(app,/function reviewSpotlight\(\)/,'Real reviews must have a homepage section');
assert.match(app,/\$\{reviewSpotlight\(\)\}/,'Home includes review section');
assert.match(app,/VeloryzReviewExperience\?\.mount/,'Navigation re-mounts carousel');
assert.match(shell,/\/review-experience\.js/,'Timed popup and carousel have a site script');
assert.match(shell,/\/review-experience\.css/,'Carousel and popup have theme styles');
assert.match(widget,/INVITE_AFTER_MS=120000/,'Invite must wait for exactly 120000 ms of active usage');
assert.match(widget,/document\.visibilityState==='visible'/,'Hidden tabs should not accumulate usage time');
assert.match(widget,/sessionStorage/,'Prompt must not keep returning in a tab');
assert.match(widget,/aria-modal/,'Pop-up must be accessible');
assert.match(widget,/closeInvite/,'Pop-up must be dismissible');
assert.match(widget,/getReviews\(\)/,'Carousel must use public reviewed feedback, not examples');
assert.match(widget,/cloneNode\(true\)/,'Continuously loop real slide set');
assert.match(style,/@keyframes vzReviewMarquee/,'Continuous motion must be defined');
assert.match(style,/linear infinite/,'Loop must not end after one pass');
assert.match(style,/prefers-reduced-motion:reduce/,'Reduced-motion users need a static list');

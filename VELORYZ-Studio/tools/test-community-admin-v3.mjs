import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const page=read('lib/reviews-page.ts');
const reviews=read('public/reviews.js');
const publicCss=read('public/reviews-simple.css');
const admin=read('public/admin.js');
const adminDetail=read('public/admin-detail.js');
const adminShell=read('lib/admin-shell.ts');
const adminReviews=read('public/admin-community.js');
const adminAI=read('public/admin-ai-control.js');
const adminCss=read('public/admin-control-v3.css');
const aiAgents=read('public/admin-knowledge-ai.js');
const aiProvider=read('public/admin-ai.js');
const route=read('lib/page-handler.ts');
for(const [name,source] of Object.entries({reviews,admin,adminDetail,adminReviews,adminAI,aiAgents,aiProvider})){
 assert.doesNotThrow(()=>new vm.Script(source,{filename:name}),name+' must parse as JavaScript');
}
const result=ts.transpileModule(page,{fileName:'reviews-page.ts',compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.equal(result.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length||0,0);
const sandbox={exports:{},module:{exports:{}}};
vm.runInNewContext(result.outputText,sandbox,{timeout:2500});
const html=sandbox.exports.renderReviewsPage(false);
for(const text of ['Community Feedback','Start Rating','All ratings','data-review-rating="5"','data-review-rating="4"','data-review-rating="3"','data-review-rating="2"','data-review-rating="1"','id="review-feed"','id="review-rating-distribution"'])
 assert.ok(html.includes(text),'Missing public-facing feedback control '+text);
for(const text of ['THE PEOPLE / THE PROJECTS','Your words.<br>','Our next chapter','STORIES, NOT SLOGANS','A BETTER EXPERIENCE, TOGETHER'])
 assert.ok(!html.includes(text),'Removed marketing text is still visible '+text);
assert.ok(html.indexOf('Community Feedback')<html.indexOf('id="review-feed"'),'Feedback heading precedes the reviews');
assert.match(html,/id="share-review"[^>]+hidden/,'Advanced form is not open on page load');
assert.match(reviews,/function openReview\(\)/,'Rating action must open the form');
assert.match(reviews,/dataset\.reviewRating/,'Star filters must respond to user clicks');
assert.match(reviews,/if\(location\.hash==='#share-review'\)openReview\(\)/,'Homepage and popup deep links must reveal the rating form');
assert.match(reviews,/textContent/,'Visitor content is escaped as text, not injected markup');
assert.doesNotMatch(reviews,/innerHTML\s*=/);
assert.match(publicCss,/\.feedback-hub/);
assert.match(publicCss,/prefers-reduced-motion/);
assert.match(adminShell,/\/admin-control-v3\.css/);
assert.ok(adminShell.indexOf('admin-community.js')<adminShell.indexOf('admin.js'),'Review module must load before routing');
assert.ok(adminShell.indexOf('admin-ai-control.js')<adminShell.indexOf('admin.js'),'AI module must load before routing');
assert.match(admin,/\['reviews','Community Reviews'/,'Reviews must be in the admin navigation');
assert.match(admin,/\['ai-control','AI Control Centre'/,'AI Control Centre must be in admin navigation');
assert.match(admin,/reviews:typeof adminReviewPage/,'Review workspaces must be routed');
assert.match(admin,/'ai-control':typeof aiControlPage/,'AI tools must be routed');
assert.match(admin,/loadOwnerReviews\(\)/,'Owner reviews must actually fetch');
assert.match(admin,/loadKnowledgeAi\(\)/,'Assistant settings must load');
assert.match(admin,/loadAiSettings\(\)/,'Provider settings must load');
assert.match(adminReviews,/api\('\/api\/reviews\/admin'\)/,'Private review list must come from backend');
assert.match(adminReviews,/api\('\/api\/reviews\/admin\/moderate'/,'Moderation must persist through real API');
assert.match(adminReviews,/data-review-filter/);
assert.match(adminReviews,/data-review-moderate/);
assert.match(adminReviews,/E\(review\.body/,'Do not insert unescaped user reviews into admin HTML');
assert.doesNotMatch(adminReviews,/fabricated testimonials?/i);
assert.match(adminAI,/knowledgeAiAdmin\(\)/,'AI hub must reuse working secure agent editor');
assert.match(adminAI,/aiMindsetPage\(\)/,'AI hub must reuse CMS-bound adviser editor');
assert.match(adminAI,/aiSettingsForm\(\)/,'AI hub must reuse secure provider form');
assert.match(aiAgents,/section==='ai-control'/,'AI hub must receive updated agent settings');
assert.match(aiProvider,/section==='ai-control'/,'AI hub must receive updated provider status');
assert.match(route,/\/admin\/#\/reviews/,'Legacy review admin path must open native admin route');
assert.match(adminCss,/\.ad-review-grid/);
assert.match(adminCss,/\.ad-ai-hub-tabs/);
assert.match(adminCss,/@media\(max-width:480px\)/);
assert.match(adminCss,/prefers-reduced-motion/);
console.log('PASS: simplified public Community Feedback, visible 5–1 ratings, start-rating flow, native review moderation and unified working AI consoles.');

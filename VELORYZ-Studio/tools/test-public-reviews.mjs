import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const root=new URL('../',import.meta.url);
const file=p=>fs.readFileSync(new URL(p,root),'utf8');
const page=file('lib/page-handler.ts');
const reviewPage=file('lib/reviews-page.ts');
const edge=file('supabase/functions/veloryz-reviews-api/index.ts');
const migration=file('supabase/migrations/20261122223000_moderated_public_reviews.sql');
const client=file('public/reviews.js');
const docs=file('public/docs-studio.js');
const hub=file('public/docs-hub.js');
const sitemap=file('public/site-map.js');
const published=file('public/app.js');
const csr=file('lib/cms-api.mjs');
const compile=ts.transpileModule(reviewPage,{fileName:'reviews-page.ts',compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.deepEqual((compile.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error).map(d=>ts.flattenDiagnosticMessageText(d.messageText,'\n')),[]);
const module={exports:{}};vm.runInNewContext(compile.outputText,{exports:module.exports,module},{timeout:2000});
const publicHtml=module.exports.renderReviewsPage(false),adminHtml=module.exports.renderReviewsPage(true);
assert.match(publicHtml,/\/reviews\.html/);
assert.match(publicHtml,/name="rating"/);
assert.match(publicHtml,/awaiting|human-moderated/i);
assert.match(adminHtml,/noindex,nofollow/);
assert.match(adminHtml,/review-admin-list/);
assert.match(client,/textContent/, 'User feedback must be rendered as text, not raw HTML');
assert.doesNotMatch(client,/innerHTML\s*=/,'Never write submitted text into innerHTML');
assert.match(edge,/status='approved'/,'Public list must include approved reviews only');
assert.match(edge,/admin\(req\)/,'Moderation must authenticate the studio owner');
assert.match(edge,/await throttle\(req,'submit',3,86400\)/);
assert.match(migration,/ENABLE ROW LEVEL SECURITY/);
assert.match(migration,/REVOKE ALL ON TABLE.*FROM PUBLIC, anon, authenticated/);
assert.match(csr,/forwardReviews\(request\)/);
assert.match(page,/if\(path==='\/reviews\.html'/);
assert.match(page,/htmlDocumentPath/);
assert.match(page,/reviews\.html/,'Review page must appear in XML sitemap');
assert.match(page,/roadmap\.html/,'Public project roadmap should be discoverable');
assert.match(file('lib/docs-server-html.ts'),/renderHtmlDocument/,'Initial HTML must contain actual handbook content');
assert.match(docs,/docHtmlPath/);
assert.match(hub,/docHtmlPath/);
assert.match(sitemap,/\/docs\/index\.html/);
for(const path of ['lib/defaults.json','lib/page-handler.ts','lib/search-index-content.ts','lib/site-shell.ts','public/app.js']){
 assert.doesNotMatch(file(path),/Bokaro|Bucaro|Jharkhand/i,'City-specific public text remains in '+path);
}
assert.doesNotMatch(publicHtml,/fake client|placeholder testimonial/i);
console.log('PASS: reviews are approval-only, owner-moderated, no raw HTML, rate-limited; India location and HTML documentation routes.');

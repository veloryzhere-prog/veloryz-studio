import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext,Script} from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('public/admin-docs.js'),handler=read('lib/page-handler.ts'),renderer=read('lib/knowledge-v8.ts'),shell=read('lib/admin-shell.ts');
new Script(source);
const {norm,effective,select,draftIssues,linkTargets}=runInNewContext(source.slice(source.indexOf('const norm='),source.indexOf('let items='))+';({norm,effective,select,draftIssues,linkTargets})',{URL});
const a={path:'/docs/a',title:'Alpha',summary:'Help',markdown:'Text',status:'guide',category:'Help'},b={...a,path:'/docs/b',title:'Beta',status:'draft'};
assert.equal(norm('/docs/a.html'),'/docs/a');
assert.equal(norm('/docs/index.html'),'/docs');
assert.equal(effective(a,{markdown:''}).markdown,'Text');
assert.equal(effective(a,{visible:false}).visible,false);
assert.equal(select([a,b],{},'beta','all','review')[0].path,b.path);
assert.equal(select([a,b],{'/docs/a':{visible:false}},'','all','hidden')[0].path,a.path);
assert.equal(draftIssues({...a,markdown:'x'.repeat(25001)}).length,1);
assert.equal(draftIssues(a).length,0);
const links=linkTargets('[A](/docs/a.html) [A2](/docs/a.html#part) [Private](/admin/) [API](/api/site) [External](https://example.com/) [Same](https://veloryz.online/help/studio/index.html) [Hash](#part)','https://veloryz.online');
assert.deepEqual([...links.local],['/docs/a.html','/help/studio/index.html']);
assert.equal(links.other.length,4);
assert.equal(linkTargets('~~~\n[Code](/docs/a.html)\n~~~','https://veloryz.online').local.length,0);
assert.match(renderer,/export function documentationSource/);
assert.match(renderer,/markdown:a\.body/);
assert.match(handler,/if\(path==='\/admin\/docs-source'\)/);
assert.match(handler,/const owner=await handleApi/);
assert.ok(handler.indexOf('if(!owner.ok)')<handler.indexOf('const result=documentationSource'));
assert.match(source,/paths=targets\.local\.slice\(0,8\)/);
assert.match(source,/credentials:'omit',redirect:'manual'/);
assert.match(shell,/admin-docs\.js\?v=20261127-r51-10/);
console.log('R51.10 documentation source, review semantics, link policy and owner route contract passed.');

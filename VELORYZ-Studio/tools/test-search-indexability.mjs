import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const root=new URL('../',import.meta.url);
const get=p=>readFileSync(new URL(p,root),'utf8');
const page=get('lib/page-handler.ts');
const origin=get('lib/site-origin.mjs');
const response=get('lib/response-security.ts');
const indexable=get('lib/search-index-content.ts');
const app=get('public/app.js');
const verify=get('public/googleb802659617480672.html');
const compiled=ts.transpileModule(indexable,{fileName:'search-index-content.ts',compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.deepEqual((compiled.diagnostics||[]).filter(x=>x.category===ts.DiagnosticCategory.Error).map(x=>ts.flattenDiagnosticMessageText(x.messageText,'\n')),[],'SEO markup module must compile.');
const exports={};
vm.runInNewContext(compiled.outputText,{exports,module:{exports}}, {timeout:2000});
const {renderIndexableBody}=exports;
assert.equal(typeof renderIndexableBody,'function');
const html=renderIndexableBody('/','VELORYZ Studio','Creative and technology studio');
assert.equal((html.match(/<h1\b/g)||[]).length,1,'Homepage initial HTML needs one H1.');
assert.match(html,/Built to be/);
assert.match(html,/VELORYZ Studio/);
const text=html.replace(/<[^>]*>/g,' ').replace(/&amp;/g,'&').replace(/\s+/g,' ').trim();
assert.ok(text.split(' ').length>=155,'Meaningful static homepage needs 155+ real descriptive words, not a 28-word empty app shell.');
for(const path of ['/services','/work','/studio','/design','/create','/pricing','/contact','/process']){
 const rendered=renderIndexableBody(path,'Test','Test');
 assert.equal((rendered.match(/<h1\b/g)||[]).length,1, 'Missing first-response H1: '+path);
 assert.ok(rendered.includes('VELORYZ'),'Brand name missing from initial markup: '+path);
 assert.match(rendered,/<a href="\/(?:services|work|create|contact|pricing|studio)"/,'Important links should be crawlable before JavaScript.');
}
assert.match(renderIndexableBody('/studio','Studio','Studio'),/Valoryz, Valories or Valerie’s Studio/,'Mention human spelling variations naturally, without fabricating business aliases.');
assert.match(app,/Valoryz, Valories or Valerie’s Studio/,'Brand spellings should also be visible to real visitors in the interactive studio page.');
assert.match(page,/if\(known\)html=html\.replace\('<main id="main" tabindex="-1"><\/main>',/,'Initial semantic content must enter the real server response.');
assert.match(page,/renderIndexableBody\(normal,pages\[normal\],description\)/,'SSR content must be route-specific.');
assert.match(page,/name:'VELORYZ Studio',alternateName:\['VELORYZ','Veloryz Studio'\]/,'Only real brand aliases belong in WebSite JSON-LD.');
assert.match(response,/"@type":"Organization"/,'Organization identity should be published.');
assert.match(response,/"@id":new URL\(url\).origin\+"\/#organization"/,'Organization schema should be connected to WebSite publisher.');
assert.match(response,/name:"VELORYZ Studio"/,'Org schema must use the official studio name.');
assert.match(page,/'VELORYZ Studio \| Website Design, Development & Creative Technology'/,'Distinctive branded title in server-rendered head.');
assert.match(app,/VELORYZ Studio \| Website Design, Development & Creative Technology/,'SPA browser title matches initial HTML.');
assert.ok(!app.includes("url=canonicalOrigin+(currentRoute==='/'?'/':currentRoute);"),'SPA must not reintroduce redirecting trailing-slash canonicals.');
assert.match(app,/currentRoute\.replace\(\/\\\/\+\$\/,''\)/,'SPA must strip trailing slashes from canonical for non-root routes.');
assert.match(origin,/return clean&&clean!=='\/'\?clean:'\/'/,'Canonical paths should match observed no-trailing-slash live URLs.');
assert.match(page,/base\+canonicalPath\(p\)/,'Sitemap should use canonicalPath.');
assert.match(page,/Disallow: \/client\\n/,'Private client routes must remain excluded from crawler access.');
assert.equal(verify,'google-site-verification: googleb802659617480672.html','Exact Search Console ownership file must remain intact.');
assert.ok(page.indexOf("if(path==='/googleb802659617480672.html')")<page.indexOf("const data=await getPublished"),'Verification route must be served before dynamic CMS.');
assert.match(page,/secureHtml\(html,known\?200:404\)/,'Unknown URLs must still be real HTTP 404s.');
console.log('PASS: brand-first SSR text and H1, links, canonical/sitemap consistency, real WebSite identity, spelling guidance, verification and privacy.');

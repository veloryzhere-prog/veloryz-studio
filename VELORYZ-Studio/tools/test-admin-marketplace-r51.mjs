import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext,Script} from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('public/admin-platform.js');
new Script(source);
const {mkRunnable,mkRights,mkSelect,mkProposal}=runInNewContext(source.slice(source.indexOf('function mkRunnable'),source.indexOf('function mkMoney'))+';({mkRunnable,mkRights,mkSelect,mkProposal})');
const data=JSON.parse(read('public/veloryz-open-designs.json'));
const items=data.items;
assert.ok(items.length>0);
assert.equal(new Set(items.map(d=>d.id)).size,items.length);
assert.equal(mkSelect(items,'','all','all','curated').length,items.length);
assert.equal(mkSelect(items,'','all','runnable','curated').length,items.filter(mkRunnable).length);
assert.equal(mkSelect(items,'','all','visual','curated').length,items.filter(d=>!mkRunnable(d)).length);
assert.equal(mkRights({}), 'review');
assert.equal(mkRights({rights:'candidate',license:'CC BY-NC'}),'restricted');
assert.equal(mkRights({rights:'candidate',license:'MIT'}),'candidate');
assert.equal(mkRunnable({id:'a-test',importStatus:'real-upstream-html',localSource:'/untrusted.html'}),false);
assert.ok(mkSelect(items,'','all','low','curated').length===0);
const sorted=mkSelect(items,'','all','all','low');
assert.ok(sorted.every((d,i)=>!i||Number(sorted[i-1].price)<=Number(d.price)));
const d=items[0];const proposal=mkProposal(d,6000,false);
assert.equal(proposal.id,d.id);
assert.equal(proposal.expected.price,d.price);
assert.equal(proposal.changes.enabled,false);
assert.throws(()=>mkProposal(d,50001,true),/amount/);
assert.throws(()=>mkProposal(d,6000,'false'),/visibility/);
assert.match(source,/Saving or publishing the website CMS does not apply these proposals/);
assert.match(source,/function legacyCatalogueAdmin/);
assert.match(read('lib/admin-shell.ts'),/admin-platform\.js\?v=20261126-r51-8/);
console.log('R51.8 marketplace inventory, source identity, filtering and proposal contract passed.');

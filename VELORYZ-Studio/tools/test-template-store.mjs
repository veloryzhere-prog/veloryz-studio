/* Original VELORYZ template shop release gate: product IP, generated working pages, shopping request integrity. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {join} from 'node:path';
import {templates} from '../scripts/template-products.mjs';
import {renderTemplate,coverSVG} from '../scripts/template-showcase.mjs';
const root=join(import.meta.dirname,'..'),read=x=>fs.readFileSync(join(root,x),'utf8');
const catalog=JSON.parse(read('public/veloryz-template-products.json'));
assert.equal(templates.length,12,'Original template count changed unexpectedly');
assert.equal(catalog.length,12,'Browser catalog must contain all twelve original site templates');
assert.equal(new Set(catalog.map(p=>p.id)).size,12,'Product identifiers must be unique');
assert.equal(new Set(catalog.map(p=>p.name)).size,12,'Product names must be distinct');
const creator=read('public/creator-v4.js'),platform=read('public/platform.js'),store=read('public/template-store.js'),shell=JSON.parse(read('lib/site-shell.ts').replace(/^export default\s*/,'').replace(/;\s*$/,''));
const storeCSS=read('public/template-store.css'),previewCSS=read('public/template-preview.css'),runtime=read('public/template-preview-runtime.js');
for(const p of catalog){
 assert.ok(Number.isInteger(p.price)&&p.price>=1000,'Template must have meaningful, positive INR price');
 assert.equal(p.currency,undefined,'Browser catalog is price-denominated in INR by storefront policy');
 assert.ok(p.description.length>=70,'Template copy should describe a real design');
 assert.ok(p.features.length>=4,'Template needs detailed included front-end capabilities');
 assert.ok(p.license.includes('one')||p.license.includes('One'),'Commercial-use license must be explicit');
 assert.match(p.cover,/^\/template-covers\/[a-z0-9-]+\.svg$/);
 assert.match(p.preview,/^\/template-previews\/[a-z0-9-]+\.html$/);
 assert.ok(creator.includes("['"+p.id+"'"),'Creator preset must match template ID '+p.id);
 const file='public/template-previews/'+p.id+'.html',svg='public/template-covers/'+p.id+'.svg';
 assert.ok(fs.existsSync(join(root,file)),'Missing actual working template preview '+file);
 assert.ok(fs.existsSync(join(root,svg)),'Missing original product cover SVG '+svg);
 const html=read(file),vector=read(svg);
 assert.ok(html.includes('data-vz-preview="'+p.id+'"'),'Missing precise per-design identity');
 assert.ok(html.includes('template-preview-runtime.js'),'Interactive script missing');
 assert.ok(html.includes('template-preview.css'),'Style layer missing');
 assert.ok(html.includes('Fictional showcase content'),'Demo copy must not pretend real client work');
 assert.ok(html.includes('noindex'),'Demo websites must not compete with Studio public SEO');
 assert.ok(html.includes('prefers')||previewCSS.includes('prefers-reduced-motion'),'Motion must be optional for accessibility');
 assert.ok(html.includes('target="_top"'),'Template demos must lead back to the Studio store');
 assert.ok(vector.startsWith('<svg')&&vector.includes('Original website')===false,'Template cover should be generated first-party vector markup');
 assert.ok(html.length>4000,'A screenshot-only placeholder is not a working website '+p.id);
 assert.ok(renderTemplate(templates.find(t=>t.id===p.id)).includes('demo-header'),'Template generation must be deterministic');
 assert.ok(coverSVG(templates.find(t=>t.id===p.id)).includes('<foreignObject'),'Original SVG cover must be generated from registry');
}
assert.ok(store.includes('data-enquiry'),'Template purchase requests must reach existing studio inbox');
assert.ok(store.includes('name="kind" value="project"'),'Use validated Studio project enquiry endpoint');
assert.ok(store.includes("data-request-id="),'Idempotent order request must include a UUID');
assert.ok(store.includes("!=='Escape'")&&store.includes('data-vz-cart-close'),'Cart must close by keyboard and button');
assert.ok(store.includes('no charges')||store.includes('No charges'),'No unconnected payment claim may appear');
assert.ok(store.includes('vz-store')&&store.includes('p.cover')&&store.includes('p.preview'),'Working source, cover images and live preview must be wired to products');
assert.ok(shell.includes('veloryz-template-products.js')&&shell.includes('template-store.js')&&shell.includes('template-store.css'));
assert.ok(platform.includes('VeloryzTemplateStore?.render()'),'Design route must be the real Studio template store');
assert.ok(creator.includes('v4-template-live-art')&&creator.includes("params.get('template')"),'Create Project must use real template products and preserve selection');
assert.ok(!store.includes('Reference by'),'Repackaged third-party references must not be sold');
for(const [file,code] of [['public/template-store.js',store],['public/template-preview-runtime.js',runtime],['public/creator-v4.js',creator],['public/platform.js',platform]])assert.doesNotThrow(()=>new Function(code),'Invalid public JS: '+file);
for(const [file,code] of [['public/template-store.css',storeCSS],['public/template-preview.css',previewCSS]])assert.equal(code.split('{').length,code.split('}').length,'Unbalanced CSS '+file);
console.log('PASS: 12 original VELORYZ template websites, responsive previews, licensable storefront, working demos and validated order requests.');
